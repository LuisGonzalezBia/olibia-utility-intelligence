/**
 * Catálogo de empresas del sector energético colombiano para el registro.
 *
 * Se construye de DOS fuentes, y el orden importa:
 *
 * 1. **Agentes con ranking de tarifas** (`hasRanking: true`) — salen de
 *    `energy.comp_ranking_market_monthly` en bia-gold. Su `id` ES el `provider`
 *    de esa matview, que es su llave primaria real; por eso resaltar la fila de
 *    quien se registra funciona sin ningún mapeo intermedio.
 * 2. **El resto del sector** (`hasRanking: false`) — del `ListadoAgentes` de XM
 *    (fuente oficial, filtrado a `State=OPERACION`). Cubre generadores,
 *    transportadores y comercializadores sin tarifa publicada. Su `id` es el
 *    código SIC.
 *
 * Por qué NO se mapea XM → gold: los nombres no coinciden y no hay puente
 * confiable. `AFINIA` en el ranking es `CARIBEMAR DE LA COSTA S.A.S. E.S.P.` en
 * XM (nombre comercial vs. razón social); `QIENERGY` es `QI ENERGY`. Un
 * matcheo automático resuelve solo 14 de 44, y adivinar el resto le asignaría a
 * un usuario la empresa equivocada. El propio DDL de gold reconoce la deuda:
 * "its provider name does not match the canonical comer list — revisit when
 * there is a stable mapping".
 *
 * El usuario SIEMPRE ve el nombre común (`name`), nunca un código ni la razón
 * social con sufijos societarios.
 *
 * Generado 2026-08-10. Regenerar cuando cambie el universo de agentes.
 */

