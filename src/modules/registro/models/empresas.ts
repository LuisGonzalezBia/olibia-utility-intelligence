export const getEmpresaById = (id: string): EmpresaOption | undefined =>
  EMPRESAS.find((e) => e.id === id);

/**
 * Una empresa puede tener varios `EmpresaOption` — uno por actividad
 * (comercialización, distribución, generación...), cada uno con su propio SIC
 * o `provider`. Ej.: "AIR-E" tiene tres códigos SIC (CSIC/CSID/CSIG) y
 * "VOLTAJE EMPRESARIAL" tiene dos. Para el usuario es UNA empresa, así que el
 * buscador la muestra una sola vez y solo pregunta la actividad cuando hace
 * falta desambiguar.
 */
export interface EmpresaGroup {
  name: string;
  options: readonly EmpresaOption[];
  /** true si CUALQUIERA de sus actividades tiene tarifa publicada. */
  hasRanking: boolean;
}

const buildEmpresaGroups = (): readonly EmpresaGroup[] => {
  const byName = new Map<string, EmpresaOption[]>();
  for (const empresa of EMPRESAS) {
    const existing = byName.get(empresa.name);
    if (existing === undefined) byName.set(empresa.name, [empresa]);
    else existing.push(empresa);
  }
  // La clave del Map ya ES el nombre del grupo, así que no hace falta leerlo
  // de `options[0]` (que el tipo no puede garantizar que exista).
  return Array.from(byName, ([name, options]) => ({
    name,
    options,
    hasRanking: options.some((o) => o.hasRanking),
  }));
};

export const EMPRESA_GROUPS: readonly EmpresaGroup[] = buildEmpresaGroups();
